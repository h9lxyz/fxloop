package org.lab59.fxloop.server.export

import com.fasterxml.jackson.databind.JsonNode
import com.fasterxml.jackson.databind.node.ObjectNode
import org.lab59.fxloop.server.loop.JournalEntry
import java.util.TreeSet

/**
 * Turns a session journal into a TestFX (JUnit 5) test. The output is a draft: assertions are synthesized from the
 * recorded scene-diff effects and everything ambiguous is marked `TODO(fxloop)`.
 *
 * The generated sources are Java (they are emitted into the user's Java test tree).
 */
object TestExporter {
    /** @property steps number of journal steps replayed; @property todos number of `TODO(fxloop)` markers */
    data class Export(
        val className: String,
        val testSource: String,
        val helperSource: String,
        val steps: Int,
        val todos: Int,
    )

    private val ID_SEG = Regex("^([A-Za-z_$][\\w$.]*)#([^\\[\\]/]+)$")
    private val LABELED = setOf(
        "Label", "Button", "CheckBox", "RadioButton", "ToggleButton",
        "Hyperlink", "MenuButton", "SplitMenuButton", "TitledPane",
    )
    private val TEXT_INPUT = setOf("TextField", "TextArea", "PasswordField")

    fun export(name: String, pkg: String?, appClass: String, entries: List<JournalEntry>): Export {
        val className = name + "GeneratedTest"
        val g = Gen()
        for (e in entries) g.step(e)

        val out = StringBuilder()
        out.append("// Generated by fxloop from the session journal — generated draft, review before trusting.\n")
        if (!pkg.isNullOrBlank()) out.append("package ").append(pkg).append(";\n")
        out.append('\n')
        val imports = TreeSet(g.imports)
        imports.add("javafx.stage.Stage")
        imports.add("org.junit.jupiter.api.Test")
        imports.add("org.junit.jupiter.api.extension.ExtendWith")
        imports.add("org.testfx.api.FxRobot")
        imports.add("org.testfx.framework.junit5.ApplicationExtension")
        imports.add("org.testfx.framework.junit5.Start")
        imports.add("org.testfx.util.WaitForAsyncUtils")
        for (i in imports) out.append("import ").append(i).append(";\n")
        out.append("\n@ExtendWith(ApplicationExtension.class)\n")
        out.append("class ").append(className).append(" {\n\n")
        out.append("    @Start\n    void start(Stage stage) throws Exception {\n")
        out.append("        new ").append(appClass).append("().start(stage);\n    }\n\n")
        out.append("    @Test\n    void replaysJournal(FxRobot robot) {\n")
        out.append(g.body)
        out.append("    }\n}\n")

        return Export(className, out.toString(), helperSource(pkg), entries.size, g.todos)
    }

    // ------------------------------------------------------------------------------------------------------------

    private class Gen {
        val body = StringBuilder()
        val imports = LinkedHashSet<String>()
        var todos = 0

        fun line(s: String) {
            body.append("        ").append(s).append('\n')
        }

        fun todo(s: String) {
            todos++
            line("// TODO(fxloop): $s")
        }

        fun step(e: JournalEntry) {
            body.append('\n')
            line("// step ${e.seq}: ${e.tool}" + if (e.source == "human") " (recorded from the developer's own input)" else "")
            if (e.redacted) {
                todo("step ${e.seq} edited a password field; its value was not recorded — enter it by hand")
                return
            }
            val args = e.args
            when (e.tool) {
                "fx_click_node" -> click(e)
                "fx_set_text" -> setText(e)
                "fx_type_keys" -> typeKeys(e)
                "fx_set_property" -> {
                    val path = txt(args, "path", "")
                    todo(
                        "set property " + str(txt(args, "name", "?")!!) + " on " + str(path!!) + " to " +
                            str(if (!args.has("value")) "null" else args.get("value").toString()) +
                            " has no generic replay; set it in the app code or via robot.interact",
                    )
                }
                else -> todo("unsupported tool ${e.tool}")
            }
            line("WaitForAsyncUtils.waitForFxEvents();")
            assertions(e.effects)
        }

        // ---- targets ------------------------------------------------------------------------------------------

        /** Returns `[kind, expr]` where kind is "css", "text" or "path". Emits the TODO for path fallback. */
        fun target(path: String?, target: ObjectNode?): Array<String> {
            var fxId: String? = null
            if (path != null) {
                val m = ID_SEG.matchEntire(lastSegment(path))
                if (m != null) fxId = m.groupValues[2]
            }
            if (fxId == null && target != null && target.hasNonNull("fxId") && target.get("fxId").asText().isBlank().not()) {
                fxId = target.get("fxId").asText()
            }
            if (fxId != null) return arrayOf("css", str("#$fxId"))
            val text = if (target != null && target.hasNonNull("text")) target.get("text").asText() else ""
            if (text.isNotBlank() && !text.startsWith("#") && !text.startsWith(".")) {
                return arrayOf("text", str(text))
            }
            todo("no fx:id — prefer adding one (${path ?: "?"})")
            // keep the marker adjacent to the use: the TODO line is already emitted above the statement
            return arrayOf("path", "FxPath.lookup(robot, " + str(path ?: "") + ")")
        }

        fun click(e: JournalEntry) {
            val a = e.args
            var path = txt(a, "path", null)
            val hasXY = a.hasNonNull("x") && a.hasNonNull("y") && path == null
            val button = txt(a, "button", "primary")!!.lowercase()
            val count = if (a.hasNonNull("clickCount")) a.get("clickCount").asInt(1) else 1
            val btn = when (button) {
                "secondary" -> "MouseButton.SECONDARY"
                "middle" -> "MouseButton.MIDDLE"
                else -> null
            }
            if (btn != null) imports.add("javafx.scene.input.MouseButton")
            val bArg = if (btn == null) "" else ", $btn"
            if (hasXY) {
                todo("screen coordinates are fragile — prefer a node target")
                val xy = a.get("x").asText() + ", " + a.get("y").asText()
                repeat(count, "robot.clickOn($xy$bArg)", "robot.doubleClickOn($xy$bArg)")
                return
            }
            if (path == null && e.target != null) path = txt(e.target, "path", null)
            val expr = target(path, e.target)[1]
            repeat(count, "robot.clickOn($expr$bArg)", "robot.doubleClickOn($expr$bArg)")
        }

        fun repeat(count: Int, single: String, dbl: String) {
            if (count == 2) {
                line("$dbl;")
            } else {
                repeat(maxOf(1, count)) { line("$single;") }
            }
        }

        fun setText(e: JournalEntry) {
            val a = e.args
            var path = txt(a, "path", null)
            if (path == null && e.target != null) path = txt(e.target, "path", null)
            val text = txt(a, "text", "")!!
            val clear = !a.hasNonNull("clearFirst") || a.get("clearFirst").asBoolean(true)
            val t = target(path, e.target)
            imports.add("javafx.scene.control.TextInputControl")
            val node = if (t[0] == "path") "((TextInputControl) ${t[1]})"
            else "robot.lookup(${t[1]}).queryAs(TextInputControl.class)"
            line("robot.interact(() -> " + node + (if (clear) ".setText(" else ".appendText(") + str(text) + "));")
        }

        fun typeKeys(e: JournalEntry) {
            val a = e.args
            val path = txt(a, "path", null)
            if (path != null) {
                val t = target(path, e.target)
                line("robot.clickOn(${t[1]}); // focus the target before typing")
            }
            val keys = a.get("keys")
            if (keys == null || !keys.isArray || keys.isEmpty) {
                todo("fx_type_keys without keys")
                return
            }
            imports.add("javafx.scene.input.KeyCode")
            for (k in keys) {
                val codes = ArrayList<String>()
                val mods = k.get("modifiers")
                if (mods != null && mods.isArray) {
                    for (m in mods) codes.add("KeyCode." + keyName(m.asText()))
                }
                codes.add("KeyCode." + keyName(k.path("code").asText("UNDEFINED")))
                line("robot.push(" + codes.joinToString(", ") + ");")
            }
        }

        fun keyName(s: String): String = when (val u = s.trim().uppercase()) {
            "CTRL" -> "CONTROL"
            "CMD", "COMMAND" -> "COMMAND"
            else -> u
        }

        // ---- assertions ---------------------------------------------------------------------------------------

        fun assertions(fx: ObjectNode?) {
            if (fx == null) return
            val byPath = LinkedHashMap<String, MutableList<JsonNode>>()
            val changed = fx.get("changed")
            if (changed != null && changed.isArray) {
                for (c in changed) byPath.getOrPut(c.path("path").asText("")) { ArrayList() }.add(c)
            }
            val covered = ArrayList<String>()
            for ((path, nodes) in byPath) {
                val m = ID_SEG.matchEntire(lastSegment(path))
                val type = m?.groupValues?.get(1)
                val id = m?.groupValues?.get(2)
                for (c in nodes) {
                    val prop = c.path("prop").asText()
                    val nv = if (c.path("new").isNull) null else c.path("new").asText()
                    val ov = if (c.path("old").isNull) null else c.path("old").asText()
                    if (prop == "focused") {
                        line("// focus: ${oneLine(path)} $ov -> $nv")
                        continue
                    }
                    val q = if (id == null) null else str("#$id")
                    val a = if (id == null || nv == null) null else assertion(q!!, type, prop, nv)
                    if (a == null) {
                        todo("verify ${oneLine(path)} $prop $ov -> $nv")
                    } else {
                        line(a)
                        if (prop == "itemCount") covered.add(path)
                    }
                }
            }
            val added = fx.get("added")
            if (added != null && added.isArray) {
                for (n in added) {
                    val text = n.path("text").asText("")
                    if (text.isBlank()) continue
                    val p = n.path("path").asText("")
                    val under = covered.any { p.startsWith("$it/") }
                    if (!under) todo("verify added ${n.path("type").asText("?")} ${str(text)}")
                }
            }
            val wc = fx.get("windowChanges")
            if (wc != null && wc.isArray) {
                for (w in wc) {
                    line(
                        "// window " + w.path("change").asText() + ": " + oneLine(w.path("window").asText()) +
                            (if (w.hasNonNull("title")) " \"" + oneLine(w.get("title").asText()) + "\"" else ""),
                    )
                }
            }
        }

        fun assertion(q: String, type: String?, prop: String, nv: String): String? {
            when (prop) {
                "text" -> {
                    if (type in LABELED) {
                        use("org.testfx.matcher.control.LabeledMatchers")
                        return "FxAssert.verifyThat($q, LabeledMatchers.hasText(${str(nv)}));"
                    }
                    if (type in TEXT_INPUT) {
                        use("org.testfx.matcher.control.TextInputControlMatchers")
                        return "FxAssert.verifyThat($q, TextInputControlMatchers.hasText(${str(nv)}));"
                    }
                }
                "disabled" -> {
                    use("org.testfx.matcher.base.NodeMatchers")
                    return "FxAssert.verifyThat($q, NodeMatchers." +
                        (if (nv.equals("true", ignoreCase = true)) "isDisabled" else "isEnabled") + "());"
                }
                "visible" -> {
                    use("org.testfx.matcher.base.NodeMatchers")
                    return "FxAssert.verifyThat($q, NodeMatchers." +
                        (if (nv.equals("true", ignoreCase = true)) "isVisible" else "isInvisible") + "());"
                }
                "itemCount" -> {
                    val n = nv.trim().toIntOrNull()
                    if (n != null) {
                        if (type == "TableView") {
                            use("org.testfx.matcher.control.TableViewMatchers")
                            return "FxAssert.verifyThat($q, TableViewMatchers.hasNumRows($n));"
                        }
                        if (type == "ListView") {
                            use("org.testfx.matcher.control.ListViewMatchers")
                            return "FxAssert.verifyThat($q, ListViewMatchers.hasItems($n));"
                        }
                    }
                }
                "value" -> {
                    if (type == "ComboBox") {
                        use("org.testfx.matcher.control.ComboBoxMatchers")
                        return "FxAssert.verifyThat($q, ComboBoxMatchers.hasSelectedItem(${str(nv)}));"
                    }
                }
            }
            return null
        }

        fun use(imp: String) {
            imports.add(imp)
            imports.add("org.testfx.api.FxAssert")
        }
    }

    // ------------------------------------------------------------------------------------------------------------

    private fun lastSegment(path: String): String = path.substring(path.lastIndexOf('/') + 1)

    private fun txt(n: ObjectNode?, f: String, dflt: String?): String? =
        if (n != null && n.hasNonNull(f)) n.get(f).asText() else dflt

    private fun oneLine(s: String?): String = s?.replace(Regex("[\\r\\n]+"), " ") ?: ""

    /** Quoted, escaped Java string literal. */
    internal fun str(s: String): String {
        val b = StringBuilder("\"")
        for (c in s) {
            when (c) {
                '"' -> b.append("\\\"")
                '\\' -> b.append("\\\\")
                '\n' -> b.append("\\n")
                '\r' -> b.append("\\r")
                '\t' -> b.append("\\t")
                '\b' -> b.append("\\b")
                '\u000c' -> b.append("\\f")
                else ->
                    if (c.code < 0x20 || c.code == 0x7f || c.code in 0x2028..0x2029) {
                        b.append("\\u%04x".format(c.code))
                    } else {
                        b.append(c)
                    }
            }
        }
        return b.append('"').toString()
    }

    // ------------------------------------------------------------------------------------------------------------

    private fun helperSource(pkg: String?): String {
        val head = if (pkg.isNullOrBlank()) "" else "package $pkg;\n\n"
        return head + HELPER
    }

    private val HELPER = """import java.util.ArrayList;
import java.util.List;
import javafx.scene.Node;
import javafx.scene.Parent;
import javafx.scene.control.ScrollPane;
import javafx.scene.control.Tab;
import javafx.scene.control.TabPane;
import javafx.stage.PopupWindow;
import javafx.stage.Stage;
import javafx.stage.Window;
import org.testfx.api.FxRobot;

/**
 * Generated by fxloop. Resolves an fxloop logical-tree path such as
 * {@code Stage[0]/Scene/VBox/HBox[0]/TextField#nameField} to a live node.
 *
 * <p>This approximates fxloop's logical tree: the first segment picks the window ({@code Stage[i]} or
 * {@code Popup[i]} among the showing windows of that kind), {@code Scene} is a pseudo node whose only child is
 * the scene root, and each following segment matches simple class name + optional {@code #fxId} + optional
 * {@code [i]} index among same-type matches. A segment is first looked up among the direct children; if none
 * match (fxloop's tree skips skin-internal nodes, so e.g. {@code ListView/ListCell[1]} sits several levels
 * deeper) the descendants are searched. {@code //} forces a descendant search. ScrollPane and TabPane content
 * is reached by also searching {@link ScrollPane#getContent()} and {@link Tab#getContent()}.
 */
final class FxPath {

    private FxPath() {}

    static Node lookup(FxRobot robot, String path) {
        String[] segs = path.split("/", -1);
        int i = 0;
        Window window = window(segs[i++]);
        Node current = null; // null = the window's scene root level
        boolean deep = false;
        boolean atScene = false;
        for (; i < segs.length; i++) {
            String seg = segs[i];
            if (seg.isEmpty()) {
                deep = true;
                continue;
            }
            if (seg.equals("Scene")) {
                atScene = true;
                continue;
            }
            List<Node> candidates;
            if (atScene && current == null) {
                candidates = new ArrayList<>(List.of(window.getScene().getRoot()));
                atScene = false;
                candidates = matches(candidates, seg, false);
            } else if (current == null) {
                candidates = matches(List.of(window.getScene().getRoot()), seg, false);
            } else {
                candidates = matches(children(current), seg, deep);
            }
            deep = false;
            current = pick(candidates, seg, path);
        }
        if (current == null) {
            throw new IllegalStateException("FxPath: path resolves to a window, not a node: " + path);
        }
        return current;
    }

    private static Window window(String seg) {
        String type = seg.replaceAll("\\[.*", "");
        int idx = index(seg);
        List<Window> ws = new ArrayList<>();
        for (Window w : Window.getWindows()) {
            if (!w.isShowing()) {
                continue;
            }
            boolean popup = w instanceof PopupWindow;
            if (type.equals("Popup") ? popup : (type.equals("Stage") && w instanceof Stage)) {
                ws.add(w);
            }
        }
        if (idx < 0) {
            idx = 0;
        }
        if (idx >= ws.size()) {
            throw new IllegalStateException("FxPath: no showing window " + seg + " (found " + ws.size() + ")");
        }
        return ws.get(idx);
    }

    private static List<Node> matches(List<Node> start, String seg, boolean deepOnly) {
        String type = seg.replaceAll("[#\\[].*", "");
        String id = null;
        int h = seg.indexOf('#');
        if (h >= 0) {
            int end = seg.indexOf('[', h);
            id = end < 0 ? seg.substring(h + 1) : seg.substring(h + 1, end);
        }
        List<Node> direct = new ArrayList<>();
        if (!deepOnly) {
            for (Node n : start) {
                if (matchesOne(n, type, id)) {
                    direct.add(n);
                }
            }
            if (!direct.isEmpty()) {
                return direct;
            }
        }
        List<Node> found = new ArrayList<>();
        for (Node n : start) {
            collect(n, type, id, found, true);
        }
        return found;
    }

    private static void collect(Node parent, String type, String id, List<Node> out, boolean skipSelf) {
        if (!skipSelf && matchesOne(parent, type, id)) {
            out.add(parent);
        }
        for (Node c : children(parent)) {
            collect(c, type, id, out, false);
        }
    }

    private static boolean matchesOne(Node n, String type, String id) {
        boolean typeOk = false;
        // anonymous subclasses (e.g. the ComboBox popup ListView) have an empty simple name: walk up
        for (Class<?> c = n.getClass(); c != null && !typeOk; c = c.getSuperclass()) {
            typeOk = c.getSimpleName().equals(type);
            if (!c.getSimpleName().isEmpty()) {
                break;
            }
        }
        if (!typeOk) {
            return false;
        }
        return id == null || id.equals(n.getId());
    }

    private static Node pick(List<Node> candidates, String seg, String path) {
        int idx = Math.max(0, index(seg));
        if (idx >= candidates.size()) {
            throw new IllegalStateException("FxPath: segment '" + seg + "' not found in " + path
                    + " (" + candidates.size() + " match(es))");
        }
        return candidates.get(idx);
    }

    private static int index(String seg) {
        int a = seg.lastIndexOf('[');
        int b = seg.lastIndexOf(']');
        return a >= 0 && b > a ? Integer.parseInt(seg.substring(a + 1, b)) : -1;
    }

    private static List<Node> children(Node n) {
        List<Node> out = new ArrayList<>();
        if (n instanceof Parent p) {
            out.addAll(p.getChildrenUnmodifiable());
        }
        if (n instanceof ScrollPane sp && sp.getContent() != null && !out.contains(sp.getContent())) {
            out.add(sp.getContent());
        }
        if (n instanceof TabPane tp) {
            for (Tab t : tp.getTabs()) {
                if (t.getContent() != null && !out.contains(t.getContent())) {
                    out.add(t.getContent());
                }
            }
        }
        return out;
    }
}
